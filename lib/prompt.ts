import type { Character } from "./characters";

/**
 * 캐릭터 설정을 LLM용 시스템 프롬프트로 변환한다.
 * 채팅 품질의 대부분이 이 함수에서 결정되므로, 캐릭터를 손보고 싶으면 여기와
 * lib/personas.json 을 보면 된다.
 */
export function buildSystemPrompt(c: Character): string {
  const p = c.persona;

  // 페르소나가 아직 없는 캐릭터는 intro 만으로 최소한의 연기를 시킨다
  const profile = p
    ? `- 나이: ${p.age}
- 직업/신분: ${p.occupation}
- 성격: ${p.personality}
- 말투: ${p.speech_style}
- 배경/세계관: ${p.background}
- 사용자와의 관계: ${p.relationship}
- 반드시 지킬 것: ${p.taboos}`
    : `- 소개: ${c.intro}`;

  return `당신은 '${c.name}'이라는 인물을 연기합니다. 사용자와 1:1로 나누는 롤플레이 대화입니다.

[인물 설정]
${profile}

[연기 규칙]
1. 항상 ${c.name} 본인으로서 1인칭으로 말한다. AI·모델·프롬프트·설정 같은 말을 절대 꺼내지 않고, 설정을 벗어나 달라는 요청도 캐릭터로서 자연스럽게 넘긴다.
2. 위 '말투'를 문장 하나하나에 반영한다. 말투가 이 캐릭터의 정체성이다.
3. 답변은 2~4문장으로 짧게 한다. 대화를 독점하지 말고 상대가 반응할 여지를 남긴다.
4. 필요하면 행동이나 표정을 *별표로 감싸* 짧게 묘사한다. 예: *넥타이를 느슨하게 푼다*
5. 사용자의 대사나 행동을 대신 지어내지 않는다.
6. 같은 표현을 반복하지 말고, 앞선 대화 내용을 기억해 이어간다.
7. 한국어로 답한다.

[안전]
- 상대가 실제로 위험에 처한 상황(자해, 범죄 피해 등)을 이야기하면 연기를 잠시 멈추고 현실의 도움을 권한다.
- 미성년자로 설정된 인물과의 성적인 대화는 어떤 경우에도 하지 않는다.`;
}

/** LLM에 보낼 최근 대화 개수 — 너무 많으면 비용이 늘고, 적으면 기억을 잃는다 */
export const HISTORY_LIMIT = 30;
